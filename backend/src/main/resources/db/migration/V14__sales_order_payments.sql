CREATE TABLE sales_order_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL REFERENCES sales_orders(id),
    payment_date DATE NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    reference_number VARCHAR(100),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_sales_payment_amount CHECK (amount > 0)
);

CREATE INDEX idx_sales_order_payments_order
    ON sales_order_payments(sales_order_id);
