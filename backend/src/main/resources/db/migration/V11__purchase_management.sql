
-- V11: Purchase management

CREATE TABLE purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_number VARCHAR(50) NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),

    supplier_invoice_number VARCHAR(100),
    purchase_date DATE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gst_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,

    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_purchase_status
        CHECK (status IN ('DRAFT', 'RECEIVED', 'CANCELLED')),

    CONSTRAINT chk_purchase_amounts
        CHECK (
            subtotal >= 0
            AND discount_amount >= 0
            AND gst_amount >= 0
            AND total_amount >= 0
        )
);

-- Prevent duplicate non-empty supplier invoice numbers.
CREATE UNIQUE INDEX uq_purchase_supplier_invoice
    ON purchases (supplier_id, LOWER(TRIM(supplier_invoice_number)))
    WHERE supplier_invoice_number IS NOT NULL
      AND TRIM(supplier_invoice_number) <> '';

CREATE INDEX idx_purchases_supplier_date
    ON purchases (supplier_id, purchase_date DESC);

CREATE INDEX idx_purchases_status_date
    ON purchases (status, purchase_date DESC);


CREATE TABLE purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_id BIGINT NOT NULL
        REFERENCES purchases(id) ON DELETE RESTRICT,

    product_id BIGINT NOT NULL REFERENCES products(id),

    product_code VARCHAR(50) NOT NULL,
    product_name VARCHAR(150) NOT NULL,

    quantity NUMERIC(14, 3) NOT NULL,
    purchase_rate NUMERIC(14, 2) NOT NULL,

    discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gst_rate NUMERIC(5, 2) NOT NULL DEFAULT 0,
    gst_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    line_total NUMERIC(14, 2) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_purchase_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_purchase_item_rate CHECK (purchase_rate >= 0),
    CONSTRAINT chk_purchase_item_discount CHECK (discount_amount >= 0),
    CONSTRAINT chk_purchase_item_gst_rate
        CHECK (gst_rate >= 0 AND gst_rate <= 100),
    CONSTRAINT chk_purchase_item_gst_amount CHECK (gst_amount >= 0),
    CONSTRAINT chk_purchase_item_total CHECK (line_total >= 0)
);

CREATE INDEX idx_purchase_items_purchase
    ON purchase_items (purchase_id);

CREATE INDEX idx_purchase_items_product
    ON purchase_items (product_id);


CREATE TABLE purchase_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_id BIGINT NOT NULL
        REFERENCES purchases(id) ON DELETE RESTRICT,

    payment_date DATE NOT NULL,
    amount NUMERIC(14, 2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    reference_number VARCHAR(100),
    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_purchase_payment_amount CHECK (amount > 0),
    CONSTRAINT chk_purchase_payment_method
        CHECK (
            payment_method IN (
                'CASH',
                'UPI',
                'BANK_TRANSFER',
                'CHEQUE',
                'CARD',
                'OTHER'
            )
        )
);

CREATE INDEX idx_purchase_payments_purchase
    ON purchase_payments (purchase_id, payment_date DESC);
