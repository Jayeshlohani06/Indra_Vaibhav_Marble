
-- V8: Supplier management

CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    supplier_code VARCHAR(50) UNIQUE,
    name VARCHAR(150) NOT NULL,
    contact_person VARCHAR(120),
    phone VARCHAR(20),
    alternate_phone VARCHAR(20),
    email VARCHAR(150),
    gstin VARCHAR(15),

    address_line TEXT,
    city VARCHAR(100),
    state VARCHAR(100),
    postal_code VARCHAR(10),
    notes TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Allow multiple suppliers without a GSTIN,
-- but prevent duplicate non-empty GSTIN values.
CREATE UNIQUE INDEX uq_suppliers_gstin
    ON suppliers (gstin)
    WHERE gstin IS NOT NULL AND TRIM(gstin) <> '';

CREATE INDEX idx_suppliers_name
    ON suppliers (name);

CREATE INDEX idx_suppliers_active
    ON suppliers (is_active);
