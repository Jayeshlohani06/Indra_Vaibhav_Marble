    ('CASH_READ', 'View daily cash sessions and the cash book'),
    ('CASH_MANAGE', 'Open and close the day and record cash movements'),
    ('CASH_APPROVE', 'Approve cash differences and corrections, and reopen closed days')
ON CONFLICT (code) DO NOTHING;

