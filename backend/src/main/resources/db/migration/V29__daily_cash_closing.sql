-- Daily cash closing: the drawer is opened and closed once per business day,
-- counted by denomination, and every closed day locks its date so money
-- entries cannot be added or changed behind it.
--
-- Payments, refunds and expenses stay in their own tables; the cash book is
-- read from them. cash_movements only holds money that has no other home:
-- owner cash in/out, bank deposits/withdrawals and approved corrections.
-- Nothing existing is dropped or rewritten.

-- Single settings row. Closing takes a write lock on it and every money
-- entry takes a share lock, so an entry can never slip into a day while it
-- is being closed.
CREATE TABLE cash_settings (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    approval_threshold NUMERIC(14,2) NOT NULL DEFAULT 500 CHECK (approval_threshold >= 0),
    updated_by VARCHAR(255),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO cash_settings (id) VALUES (1);

CREATE TABLE cash_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'CLOSED')),
    opening_balance NUMERIC(14,2) NOT NULL CHECK (opening_balance >= 0),
    -- Counted cash of the previous closed day; NULL for the first day.
    carried_forward NUMERIC(14,2),
    opening_note VARCHAR(500),
    opened_by VARCHAR(255) NOT NULL,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expected_cash NUMERIC(14,2),
    counted_cash NUMERIC(14,2),
    difference NUMERIC(14,2),
    closing_note VARCHAR(1000),
    closed_by VARCHAR(255),
    closed_at TIMESTAMPTZ,
    approved_by VARCHAR(255),
    close_request_id UUID,
    reopen_count INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_cash_session_closed_fields CHECK (
        status = 'OPEN' OR (expected_cash IS NOT NULL AND counted_cash IS NOT NULL
            AND difference IS NOT NULL AND closed_by IS NOT NULL AND closed_at IS NOT NULL)
    )
);
-- Only one day can be open at a time.
CREATE UNIQUE INDEX uk_cash_sessions_one_open ON cash_sessions (status) WHERE status = 'OPEN';

CREATE TABLE cash_count_lines (
    session_id BIGINT NOT NULL REFERENCES cash_sessions(id) ON DELETE CASCADE,
    denomination NUMERIC(8,2) NOT NULL CHECK (denomination > 0),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    PRIMARY KEY (session_id, denomination)
);

CREATE TABLE cash_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_date DATE NOT NULL,
    movement_type VARCHAR(30) NOT NULL CHECK (movement_type IN (
        'OWNER_CASH_IN', 'OWNER_CASH_OUT', 'BANK_DEPOSIT', 'BANK_WITHDRAWAL',
        'ADJUSTMENT_IN', 'ADJUSTMENT_OUT')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    reference_number VARCHAR(100),
    notes VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'VOIDED')),
    request_id UUID UNIQUE,
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_by VARCHAR(255),
    voided_by VARCHAR(255),
    voided_at TIMESTAMPTZ,
    void_reason VARCHAR(500)
);
CREATE INDEX idx_cash_movements_date ON cash_movements (movement_date);

-- Who did what to money records, with the record before and after.
CREATE TABLE financial_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(40) NOT NULL,
    entity_id BIGINT,
    action VARCHAR(40) NOT NULL,
    actor VARCHAR(255),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason VARCHAR(1000),
    before_state TEXT,
    after_state TEXT
);
CREATE INDEX idx_financial_audit_entity ON financial_audit_log (entity_type, entity_id);
CREATE INDEX idx_financial_audit_time ON financial_audit_log (occurred_at DESC);

CREATE TABLE staff_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(20),
    job_title VARCHAR(80),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_staff_members_name ON staff_members (lower(name));

