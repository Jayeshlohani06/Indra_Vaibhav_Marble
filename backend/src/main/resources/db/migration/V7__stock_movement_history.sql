-- V7: Stock movement history
-- Records stock changes for audit and traceability.

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL,

    movement_type VARCHAR(20) NOT NULL,

    quantity_change NUMERIC(14, 3) NOT NULL,
    stock_before NUMERIC(14, 3) NOT NULL,
    stock_after NUMERIC(14, 3) NOT NULL,

    reference_type VARCHAR(30),
    reference_id BIGINT,
    reference_number VARCHAR(50),

    notes VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stock_movements_product
        FOREIGN KEY (product_id)
        REFERENCES products(id),

    CONSTRAINT chk_stock_movements_type
        CHECK (
            movement_type IN (
                'SALE',
                'PURCHASE',
                'ADJUSTMENT',
                'REVERSAL'
            )
        ),

    CONSTRAINT chk_stock_movements_quantity
        CHECK (quantity_change <> 0),

    CONSTRAINT chk_stock_movements_stock_before
        CHECK (stock_before >= 0),

    CONSTRAINT chk_stock_movements_stock_after
        CHECK (stock_after >= 0),

    CONSTRAINT chk_stock_movements_quantity_math
        CHECK (stock_after = stock_before + quantity_change)
);

CREATE INDEX idx_stock_movements_product_date
    ON stock_movements (product_id, created_at DESC);

CREATE INDEX idx_stock_movements_created_at
    ON stock_movements (created_at DESC);

CREATE INDEX idx_stock_movements_reference
    ON stock_movements (reference_type, reference_id);