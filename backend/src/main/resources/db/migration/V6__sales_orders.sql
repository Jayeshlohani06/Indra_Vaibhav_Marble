
-- Sales order header
CREATE TABLE sales_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL
        REFERENCES customers(id),
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    tax_type VARCHAR(10) NOT NULL DEFAULT 'INTRA',

    subtotal NUMERIC(14,2) NOT NULL DEFAULT 0,
    cgst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    sgst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    igst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_tax NUMERIC(14,2) NOT NULL DEFAULT 0,
    grand_total NUMERIC(14,2) NOT NULL DEFAULT 0,

    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_sales_order_status
        CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),

    CONSTRAINT chk_sales_order_tax_type
        CHECK (tax_type IN ('INTRA', 'INTER')),

    CONSTRAINT chk_sales_order_amounts
        CHECK (
            subtotal >= 0
            AND cgst_amount >= 0
            AND sgst_amount >= 0
            AND igst_amount >= 0
            AND total_tax >= 0
            AND grand_total >= 0
        )
);

-- Individual products within an order.
-- Snapshot fields preserve the details used when the order was created.
CREATE TABLE sales_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL
        REFERENCES sales_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL
        REFERENCES products(id),

    product_code_snapshot VARCHAR(50) NOT NULL,
    product_name_snapshot VARCHAR(150) NOT NULL,
    unit_code_snapshot VARCHAR(20) NOT NULL,

    quantity NUMERIC(14,3) NOT NULL,
    unit_price NUMERIC(14,2) NOT NULL,
    gst_rate NUMERIC(5,2) NOT NULL DEFAULT 0,

    taxable_amount NUMERIC(14,2) NOT NULL,
    cgst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    sgst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    igst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    line_total NUMERIC(14,2) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_sales_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_sales_item_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_sales_item_gst
        CHECK (gst_rate >= 0 AND gst_rate <= 100),

    CONSTRAINT chk_sales_item_amounts
        CHECK (
            taxable_amount >= 0
            AND cgst_amount >= 0
            AND sgst_amount >= 0
            AND igst_amount >= 0
            AND line_total >= 0
        )
);

CREATE INDEX idx_sales_orders_customer
    ON sales_orders(customer_id);

CREATE INDEX idx_sales_orders_date
    ON sales_orders(order_date);

CREATE INDEX idx_sales_orders_status
    ON sales_orders(status);

CREATE INDEX idx_sales_order_items_order
    ON sales_order_items(sales_order_id);

CREATE INDEX idx_sales_order_items_product
    ON sales_order_items(product_id);
