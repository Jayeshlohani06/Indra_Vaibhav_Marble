-- Goods returned on a bill (part or all of it) and cancelled bills.
-- The original bill is never changed: each return is its own record
-- (RET-0001), and the bill keeps a running total of what was returned.
CREATE SEQUENCE IF NOT EXISTS sales_return_number_seq START WITH 1;

CREATE TABLE sales_returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL REFERENCES sales_orders(id),
    return_number VARCHAR(40) NOT NULL UNIQUE,
    return_date DATE NOT NULL,
    reason TEXT NOT NULL,
    cancels_order BOOLEAN NOT NULL DEFAULT FALSE,
    subtotal NUMERIC(14,2) NOT NULL DEFAULT 0,
    cgst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    sgst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    igst_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    charges_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    refund_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    created_by VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_sales_return_amounts CHECK (
        subtotal >= 0 AND cgst_amount >= 0 AND sgst_amount >= 0
        AND igst_amount >= 0 AND charges_amount >= 0
        AND total_amount >= 0 AND refund_amount >= 0
    )
);

CREATE INDEX idx_sales_returns_order ON sales_returns(sales_order_id);

CREATE TABLE sales_return_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_return_id BIGINT NOT NULL REFERENCES sales_returns(id) ON DELETE CASCADE,
    sales_order_item_id BIGINT NOT NULL REFERENCES sales_order_items(id),
    quantity NUMERIC(14,3) NOT NULL,
    secondary_quantity NUMERIC(14,3),
    taxable_amount NUMERIC(14,2) NOT NULL,
    cgst_amount NUMERIC(14,2) NOT NULL,
    sgst_amount NUMERIC(14,2) NOT NULL,
    igst_amount NUMERIC(14,2) NOT NULL,
    line_total NUMERIC(14,2) NOT NULL,
    CONSTRAINT chk_sales_return_item_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_sales_return_items_return ON sales_return_items(sales_return_id);
CREATE INDEX idx_sales_return_items_order_item ON sales_return_items(sales_order_item_id);

ALTER TABLE sales_orders
    ADD COLUMN returned_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    ADD COLUMN cancel_reason TEXT,
    ADD COLUMN cancelled_at TIMESTAMPTZ;

-- Refunds are stored as negative payments linked to their return, so the
-- amount paid on a bill is always the sum of its payments.
ALTER TABLE sales_order_payments
    ADD COLUMN sales_return_id BIGINT REFERENCES sales_returns(id);
ALTER TABLE sales_order_payments DROP CONSTRAINT chk_sales_payment_amount;
ALTER TABLE sales_order_payments ADD CONSTRAINT chk_sales_payment_amount CHECK (
    (sales_return_id IS NULL AND amount > 0)
    OR (sales_return_id IS NOT NULL AND amount < 0)
);

-- Stock that comes back from a customer.
ALTER TABLE stock_movements DROP CONSTRAINT chk_stock_movements_type;
ALTER TABLE stock_movements ADD CONSTRAINT chk_stock_movements_type
    CHECK (movement_type IN ('SALE', 'PURCHASE', 'ADJUSTMENT', 'REVERSAL', 'RETURN'));
