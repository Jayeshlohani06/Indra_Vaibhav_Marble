
-- V9: Inventory tracking foundation
-- Preserve existing products and stock quantities.
-- Do not create fabricated slab or packaging balances.

-- 1. Inventory settings: one configuration per product.
CREATE TABLE product_inventory_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL UNIQUE
        REFERENCES products(id),

    tracking_type VARCHAR(20) NOT NULL,

    box_coverage_sqft NUMERIC(12, 3),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_product_inventory_tracking_type
        CHECK (
            tracking_type IN ('SLAB', 'TILE', 'BAG', 'STANDARD')
        ),

    CONSTRAINT chk_product_inventory_box_coverage
        CHECK (
            box_coverage_sqft IS NULL
            OR box_coverage_sqft > 0
        ),

    CONSTRAINT chk_tile_requires_box_coverage
        CHECK (
            tracking_type <> 'TILE'
            OR box_coverage_sqft IS NOT NULL
        ),

    CONSTRAINT chk_non_tile_has_no_box_coverage
        CHECK (
            tracking_type = 'TILE'
            OR box_coverage_sqft IS NULL
        )
);

-- 2. Separate balances for unopened tile boxes,
-- loose square footage, and whole bags.
--
-- A row is created only after the product's opening
-- inventory has been verified and configured.
CREATE TABLE product_stock_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL UNIQUE
        REFERENCES products(id),

    unopened_boxes NUMERIC(14, 3) NOT NULL DEFAULT 0,
    loose_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0,
    whole_bags BIGINT NOT NULL DEFAULT 0,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_stock_balance_unopened_boxes
        CHECK (unopened_boxes >= 0),

    CONSTRAINT chk_stock_balance_loose_quantity
        CHECK (loose_quantity >= 0),

    CONSTRAINT chk_stock_balance_whole_bags
        CHECK (whole_bags >= 0)
);

-- 3. Individual marble and granite slabs.
CREATE TABLE product_slabs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL
        REFERENCES products(id),

    slab_code VARCHAR(80) NOT NULL UNIQUE,

    length_ft NUMERIC(10, 3) NOT NULL,
    width_ft NUMERIC(10, 3) NOT NULL,

    original_area_sqft NUMERIC(12, 3) NOT NULL,
    remaining_area_sqft NUMERIC(12, 3) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_product_slab_dimensions
        CHECK (length_ft > 0 AND width_ft > 0),

    CONSTRAINT chk_product_slab_original_area
        CHECK (original_area_sqft > 0),

    CONSTRAINT chk_product_slab_remaining_area
        CHECK (
            remaining_area_sqft >= 0
            AND remaining_area_sqft <= original_area_sqft
        ),

    CONSTRAINT chk_product_slab_status
        CHECK (
            status IN ('AVAILABLE', 'PARTIAL', 'SOLD', 'DAMAGED')
        )
);

CREATE INDEX idx_product_slabs_product_status
    ON product_slabs (product_id, status);

CREATE INDEX idx_inventory_settings_tracking_type
    ON product_inventory_settings (tracking_type);
