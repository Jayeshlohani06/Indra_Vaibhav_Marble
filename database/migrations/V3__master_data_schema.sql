-- =====================================================
-- V3: Master data and inventory schema
-- =====================================================

-- Product categories
CREATE TABLE product_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Measurement units
CREATE TABLE measurement_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Products
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description TEXT,

    category_id BIGINT NOT NULL
        REFERENCES product_categories(id),

    unit_id BIGINT NOT NULL
        REFERENCES measurement_units(id),

    selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    purchase_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gst_rate NUMERIC(5, 2) NOT NULL DEFAULT 0,
    stock_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0,
    low_stock_threshold NUMERIC(14, 3) NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_products_selling_price
        CHECK (selling_price >= 0),

    CONSTRAINT chk_products_purchase_price
        CHECK (purchase_price >= 0),

    CONSTRAINT chk_products_gst_rate
        CHECK (gst_rate >= 0 AND gst_rate <= 100),

    CONSTRAINT chk_products_stock
        CHECK (stock_quantity >= 0),

    CONSTRAINT chk_products_low_stock
        CHECK (low_stock_threshold >= 0)
);

-- Indexes
CREATE INDEX idx_products_name
    ON products(name);

CREATE INDEX idx_products_category_id
    ON products(category_id);

CREATE INDEX idx_products_unit_id
    ON products(unit_id);

CREATE INDEX idx_products_is_active
    ON products(is_active);

